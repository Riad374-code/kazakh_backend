# A single RLock serializes every sqlite operation AND each full refresh cycle.
# Without it, the background scheduler thread and the FastAPI request threads can
# interleave statements/transactions on the same connection, which surfaces as
# sqlite3 "bad parameter or other API misuse" errors in production (e.g. Railway).
_DB_LOCK = threading.RLock()


class _ThreadSafeConnection:
    """Wraps a sqlite3.Connection so every call is executed under _DB_LOCK.

    The app is multi-threaded (FastAPI threadpool + background scheduler) while
    sharing one SQLite connection (check_same_thread=False). Python's sqlite3
    serializes individual C calls, but statement *sequences* (read while another
    thread commits) can still raise SQLITE_MISUSE, so we guard at this level too.
    """

    _LOCKED = frozenset({"execute", "executemany", "executescript", "commit", "rollback", "close", "cursor"})

    def __init__(self, conn: sqlite3.Connection):
        self._conn = conn

    def __getattr__(self, name: str) -> Any:
        attr = getattr(self._conn, name)
        if name in self._LOCKED:
            def locked(*args, **kwargs):
                with _DB_LOCK:
                    return attr(*args, **kwargs)
            return locked
        return attr


def default_db_path() -> Path:
    """Resolves the SQLite database location, honouring platform config.

    Precedence:
      1. DATABASE_PATH - absolute or relative path to the database file
         (set this to a Railway volume mount for persistent storage).
      2. DATA_DIR      - directory that will hold the database file.
      3. Repo-relative ./data/kazakh_ai.db (local development default).
    """
    env_path = os.environ.get("DATABASE_PATH")
    if env_path:
        return Path(env_path)
    data_dir = os.environ.get("DATA_DIR")
    base = Path(data_dir) if data_dir else Path(__file__).resolve().parent.parent.parent / "data"
    return base / "kazakh_ai.db"


